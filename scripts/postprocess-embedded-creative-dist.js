function ensureMissingViteBrowserExternalShims(outDir) {
  const assetsDir = path.join(outDir, 'assets');
  const jsFiles = walkFiles(assetsDir, (filePath) => filePath.endsWith('.js'));
  const missingShimPaths = new Set();
  const externalRefPattern = /["']\.\/(__vite-browser-external-[^"']+\.js)["']/g;

  for (const jsFile of jsFiles) {
    const body = fs.readFileSync(jsFile, 'utf8');
    let match;
    while ((match = externalRefPattern.exec(body)) !== null) {
      const shimFileName = match[1];
      const shimPath = path.join(path.dirname(jsFile), shimFileName);
      if (!fs.existsSync(shimPath)) {
        missingShimPaths.add(shimPath);
      }
    }
  }

  for (const shimPath of missingShimPaths) {
    writeText(shimPath, getBrowserExternalShimBody(path.basename(shimPath)));
  }

  return missingShimPaths.size;
}

const LEGACY_EMBEDDED_ENTRY_ALIASES = [
  // 2026-06-16 production hotfix: some clients had a service-worker cached
  // app shell that still requested this removed Vite entry. Keep it as a
  // compatibility alias so those clients can boot far enough to unregister the
  // embedded service worker and reload onto the current artifact.
  'index-CeAw2BfZ.js',
];

function ensureLegacyEntryAliases(outDir, assetsDir) {
  const indexPath = path.join(outDir, 'index.html');
  if (!fs.existsSync(indexPath) || !fs.existsSync(assetsDir)) {
    return 0;
  }

  const indexHTML = fs.readFileSync(indexPath, 'utf8');
  const entryMatch = indexHTML.match(
    /<script[^>]+type=["']module["'][^>]+src=["']\/creative\/assets\/(index-[^"']+\.js)["'][^>]*>/
  );
  const currentEntryName = entryMatch?.[1];
  if (!currentEntryName) {
    return 0;
  }

  const currentEntryPath = path.join(assetsDir, currentEntryName);
  if (!fs.existsSync(currentEntryPath)) {
    return 0;
  }

  let created = 0;
  for (const aliasName of LEGACY_EMBEDDED_ENTRY_ALIASES) {
    if (aliasName === currentEntryName) {
      continue;
    }

    const aliasPath = path.join(assetsDir, aliasName);
    if (fs.existsSync(aliasPath)) {
      continue;
    }

    fs.copyFileSync(currentEntryPath, aliasPath);
    created += 1;
  }

  return created;
}

const basePath = normalizeBasePath(process.env.VITE_BASE_URL || './');
if (basePath !== '/creative') {
  process.exit(0);
}

const repoRoot = path.resolve(__dirname, '..');
const outDir = process.env.OPENTU_EMBEDDED_DIST_DIR
  ? path.resolve(process.env.OPENTU_EMBEDDED_DIST_DIR)
  : path.join(repoRoot, 'dist/apps/web');
const versionJSON = readJSON(path.join(outDir, 'version.json')) || {};
const version = typeof versionJSON.version === 'string' ? versionJSON.version : '0.0.0';

let touched = 0;

touched += ensureMissingViteBrowserExternalShims(outDir);

// sw.js is emitted after the app Vite closeBundle hook. Keep it same-origin and
// scrub standalone package names from the embedded artifact.
if (
  rewriteFile(path.join(outDir, 'sw.js'), [
    [/opentu\.local/gi, 'new-api.local'],
    [/OpenTu/gi, 'New API Creative'],
    [/aitu-app/g, 'new-api-creative'],
    [
      /https:\/\/cdn\.jsdelivr\.net\/npm\/new-api-creative@\{version\}\/\{path\}/g,
      '/creative/{path}',
    ],
    [
      /https:\/\/cdn\.jsdelivr\.net\/npm\/new-api-creative@/g,
      '/creative/',
    ],
  ])
) {
  touched += 1;
}

// Vite prod SW build no longer references a sourcemap, but a stale public
// sw.js.map can be copied by the app build before build-sw overwrites sw.js.
const staleSWMap = path.join(outDir, 'sw.js.map');
if (fs.existsSync(staleSWMap)) {
  fs.rmSync(staleSWMap, { force: true });
  touched += 1;
}

touched += ensureLegacyEntryAliases(outDir, path.join(outDir, 'assets'));

// Embedded deployments should not serve the standalone OpenTU changelog. Keep a
// tiny valid changelog shape for any defensive fetch path.
writeText(
  path.join(outDir, 'changelog.json'),
  `${JSON.stringify(
    {
      versions: [
        {
          version,
          date: new Date().toISOString().slice(0, 10),
          changes: {
            features: ['New API managed Creative embedded build'],
            fixes: [],
            improvements: ['Standalone release notes are hidden in embedded mode'],
          },
          type: 'patch',
          highlights: 'New API Creative embedded build',
        },
      ],
    },
    null,
    2
  )}\n`
);
touched += 1;

console.log(`[EmbeddedCreative] Postprocessed embedded dist final artifacts (${touched} updates)`);
